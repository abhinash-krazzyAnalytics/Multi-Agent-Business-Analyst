"""
Validates SQL generated by the Text-to-SQL Agent before it is ever
executed. This is a hard Python gate, not something the LLM can talk
its way around.

Checks:
  - Only SELECT / WITH statements allowed (read-only).
  - No forbidden keywords (INSERT, UPDATE, DELETE, DROP, ALTER,
    CREATE, ATTACH, PRAGMA, etc).
  - Only a single statement (no chained statements via ';').
  - Referenced tables must exist in the known schema.
  - A LIMIT is enforced if the query has none, to bound result size.
"""

import re
from config.settings import SQL_ROW_LIMIT
from tools.schema_tool import get_database_schema

FORBIDDEN_KEYWORDS = [
    "insert", "update", "delete", "drop", "alter", "create",
    "attach", "detach", "pragma", "vacuum", "replace into",
    "reindex", "truncate",
]


class SQLValidationError(Exception):
    pass


def validate_sql(sql: str) -> str:
    """
    Returns a safe, possibly-modified SQL string (with LIMIT appended
    if missing). Raises SQLValidationError if the query is unsafe or
    references unknown tables.
    """
    if not sql or not sql.strip():
        raise SQLValidationError("Empty SQL query.")

    stripped = sql.strip().rstrip(";")

    if ";" in stripped:
        raise SQLValidationError("Multiple SQL statements are not allowed.")

    lowered = stripped.lower()

    if not (lowered.startswith("select") or lowered.startswith("with")):
        raise SQLValidationError("Only read-only SELECT/WITH queries are allowed.")

    for keyword in FORBIDDEN_KEYWORDS:
        # word-boundary match so e.g. "created_at" column names don't false-positive
        if re.search(rf"\b{re.escape(keyword)}\b", lowered):
            raise SQLValidationError(f"Forbidden keyword detected: '{keyword}'.")

    schema = get_database_schema()
    known_tables = set(schema.keys())
    referenced = set(re.findall(r"\bfrom\s+([a-zA-Z_][a-zA-Z0-9_]*)", lowered)) | \
        set(re.findall(r"\bjoin\s+([a-zA-Z_][a-zA-Z0-9_]*)", lowered))

    unknown = referenced - known_tables
    if unknown:
        raise SQLValidationError(f"Unknown table(s) referenced: {', '.join(sorted(unknown))}")

    if "limit" not in lowered:
        stripped = f"{stripped}\nLIMIT {SQL_ROW_LIMIT}"

    return stripped